/**
 * Codegen: src/themes/_active.ts  →  hammerspoon/uber_theme.lua
 *
 * Single source of truth for design tokens lives in src/themes/. The
 * currently-selected theme is whatever `src/themes/_active.ts` re-exports
 * (rewritten by `npm run theme <name>`). This script bundles that module
 * graph in-memory with esbuild, dynamic-imports the result via a data URL,
 * and emits a Lua module that Hammerspoon's init.lua can `require("uber_theme")`.
 *
 * Only the *portable* tokens are exported (colors, simple numerics). CSS-only
 * concepts like padding shorthand, h2 margins, blur, and the className builder
 * are intentionally dropped — Hammerspoon's hs.canvas has no equivalent.
 *
 * Color format: Hammerspoon canvas uses { red=0..1, green=0..1, blue=0..1, alpha=0..1 }.
 * We convert from CSS hex (#rrggbb) and rgba(r, g, b, a) at codegen time so the
 * generated Lua is plain native tables — no parsing at HS load.
 */

import * as esbuild from "esbuild";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { writeFile, mkdir } from "node:fs/promises";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const activeSrc = join(root, "src", "themes", "_active.ts");
const outDir = join(root, "hammerspoon");
const outFile = join(outDir, "uber_theme.lua");

// Bundle the active theme module graph (_active → default, or whichever
// theme file _active currently points at). Unlike the earlier transform-only
// approach, bundling resolves the re-export chain so we get one self-contained
// ESM module back — the data-URL import can then pull `accents` / `layout` /
// `status` / `primary` straight off it without a codegen hook.
const result = await esbuild.build({
  entryPoints: [activeSrc],
  bundle: true,
  write: false,
  format: "esm",
  target: "es2022",
  logLevel: "silent",
});
const code = result.outputFiles[0].text;
const dataUrl =
  "data:text/javascript;base64," + Buffer.from(code).toString("base64");
const theme = await import(dataUrl);

// 2. CSS → Hammerspoon color converter.
function cssColorToLua(color) {
  if (typeof color !== "string") {
    throw new Error(`Expected color string, got ${typeof color}: ${color}`);
  }

  // #rrggbb
  const hex = color.match(/^#([0-9a-f]{6})$/i);
  if (hex) {
    const n = parseInt(hex[1], 16);
    const r = ((n >> 16) & 0xff) / 255;
    const g = ((n >> 8) & 0xff) / 255;
    const b = (n & 0xff) / 255;
    return luaColor(r, g, b, 1);
  }

  // rgba(r, g, b, a)  or  rgb(r, g, b)
  const rgba = color.match(
    /^rgba?\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*(?:,\s*([\d.]+)\s*)?\)$/
  );
  if (rgba) {
    const r = parseInt(rgba[1], 10) / 255;
    const g = parseInt(rgba[2], 10) / 255;
    const b = parseInt(rgba[3], 10) / 255;
    const a = rgba[4] != null ? parseFloat(rgba[4]) : 1;
    return luaColor(r, g, b, a);
  }

  throw new Error(`Cannot parse CSS color: ${color}`);
}

function luaColor(r, g, b, a) {
  const f = (n) => n.toFixed(4).replace(/\.?0+$/, "") || "0";
  return `{ red = ${f(r)}, green = ${f(g)}, blue = ${f(b)}, alpha = ${f(a)} }`;
}
function luaString(value) {
  return `"${String(value).replace(/\\/g, "\\\\").replace(/"/g, '\\"')}"`;
}

// 3. Strip "px" suffix from numeric layout tokens.
function px(value) {
  if (typeof value === "number") return value;
  const m = String(value).match(/^(-?\d+(?:\.\d+)?)px$/);
  if (!m) throw new Error(`Expected pixel value, got: ${value}`);
  return parseFloat(m[1]);
}

// 4. Build the Lua module.
//    Only portable accent fields are emitted — CSS-only fields (h2Margin,
//    smallExtra, showWarn) are dropped.
const accentColorFields = ["border", "text", "h1", "h2Muted", "smallMuted"];

function emitAccents(accents) {
  const lines = [];
  for (const [name, spec] of Object.entries(accents)) {
    lines.push(`    ${name} = {`);
    for (const field of accentColorFields) {
      lines.push(`      ${field} = ${cssColorToLua(spec[field])},`);
    }
    lines.push(`    },`);
  }
  return lines.join("\n");
}

function emitStatus(status) {
  const lines = [];
  for (const [name, color] of Object.entries(status)) {
    lines.push(`    ${name} = ${cssColorToLua(color)},`);
  }
  return lines.join("\n");
}

function emitLayout(layout) {
  // Cherry-pick fields that have a meaningful HS canvas analogue.
  return [
    `    width = ${px(layout.width)},`,
    `    radius = ${px(layout.radius)},`,
    `    borderWidth = ${px(layout.borderWidth)},`,
    `    cardBg = ${cssColorToLua(layout.cardBg)},`,
    // First family from the CSS font stack — HS uses a single name.
    `    fontFamily = ${luaString(layout.fontStack.split(",")[0].trim())},`,
  ].join("\n");
}

const lua = `-- AUTO-GENERATED by scripts/build-hammerspoon-theme.mjs
-- Source of truth: src/themes/_active.ts  →  src/themes/<active>.ts
-- DO NOT EDIT — your changes will be overwritten on the next \`npm run build\`.

return {
  accents = {
${emitAccents(theme.accents)}
  },

  status = {
${emitStatus(theme.status)}
  },

  layout = {
${emitLayout(theme.layout)}
  },
}
`;

await mkdir(outDir, { recursive: true });
await writeFile(outFile, lua, "utf8");

const accentNames = Object.keys(theme.accents);
console.log(
  `Generated ${outFile.replace(root + "/", "")}  (accents: ${accentNames.join(", ")})`
);

/**
 * Codegen: src/themes/_active.ts  →  ~/.config/slack-uber-theme/theme.css
 *
 * Companion to scripts/patch-slack-app.mjs. The patched Slack preload reads
 * this file at startup and injects it as a <style> tag, so theme switches
 * just need to rewrite this file — Slack picks up the new CSS on next launch
 * (no re-patch).
 *
 * What we override:
 *   - Slack's internal `--sk_*` CSS custom properties at :root, which feed
 *     most of its themed surfaces (sidebar, message pane, accents).
 *   - Direct selector overrides for the most-visible panes as a fallback,
 *     because Slack's variable names shift between major releases and not
 *     every surface reads from a variable.
 *
 * Coverage caveat: Slack's UI is huge and we only paint the obvious panes.
 * Iterate by opening Slack DevTools (Help → Troubleshoot → Open Developer
 * Tools, after enabling devtools via SLACK_DEVELOPER_MENU=true) and adding
 * selectors here as you find them.
 */

import * as esbuild from "esbuild";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { readFile, writeFile, mkdir } from "node:fs/promises";
import { homedir } from "node:os";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const activeSrc = join(root, "src", "themes", "_active.ts");
const outDir = join(homedir(), ".config", "slack-uber-theme");
const outFile = join(outDir, "theme.css");

const result = await esbuild.build({
  entryPoints: [activeSrc],
  bundle: true,
  write: false,
  format: "esm",
  target: "es2022",
  logLevel: "silent",
});
const dataUrl =
  "data:text/javascript;base64," +
  Buffer.from(result.outputFiles[0].text).toString("base64");
const theme = await import(dataUrl);

const activeSrcText = await readFile(activeSrc, "utf8");
const nameMatch = activeSrcText.match(/from\s+["'].\/([^"']+?)(?:\.js)?["']/);
const themeName = nameMatch ? nameMatch[1] : "custom";

// ---------------------------------------------------------------------------
// Color helpers (shared with the legacy-string codegen — duplicated rather
// than factored to keep each codegen self-contained)
// ---------------------------------------------------------------------------

function parseColor(color) {
  const hex6 = color.match(/^#([0-9a-f]{6})$/i);
  if (hex6) {
    const n = parseInt(hex6[1], 16);
    return { r: (n >> 16) & 0xff, g: (n >> 8) & 0xff, b: n & 0xff, a: 1 };
  }
  const rgba = color.match(
    /^rgba?\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*(?:,\s*([\d.]+)\s*)?\)$/
  );
  if (rgba) {
    return {
      r: parseInt(rgba[1], 10),
      g: parseInt(rgba[2], 10),
      b: parseInt(rgba[3], 10),
      a: rgba[4] != null ? parseFloat(rgba[4]) : 1,
    };
  }
  throw new Error(`Cannot parse CSS color: ${color}`);
}

function composite(fg, bg) {
  const a = fg.a;
  return {
    r: Math.round(fg.r * a + bg.r * (1 - a)),
    g: Math.round(fg.g * a + bg.g * (1 - a)),
    b: Math.round(fg.b * a + bg.b * (1 - a)),
    a: 1,
  };
}

function toHex(c) {
  const hh = (n) =>
    Math.min(255, Math.max(0, n)).toString(16).padStart(2, "0").toUpperCase();
  return `#${hh(c.r)}${hh(c.g)}${hh(c.b)}`;
}

function cssToHex(color, bgColor) {
  const fg = parseColor(color);
  if (fg.a >= 1) return toHex(fg);
  const bg = bgColor ? parseColor(bgColor) : { r: 0, g: 0, b: 0, a: 1 };
  return toHex(composite(fg, bg));
}

function lighten(hex, amount) {
  const c = parseColor(hex);
  return toHex({
    r: Math.round(c.r + (255 - c.r) * amount),
    g: Math.round(c.g + (255 - c.g) * amount),
    b: Math.round(c.b + (255 - c.b) * amount),
    a: 1,
  });
}

function darken(hex, amount) {
  const c = parseColor(hex);
  return toHex({
    r: Math.round(c.r * (1 - amount)),
    g: Math.round(c.g * (1 - amount)),
    b: Math.round(c.b * (1 - amount)),
    a: 1,
  });
}

// ---------------------------------------------------------------------------
// Compute the palette
// ---------------------------------------------------------------------------

const bgParsed = parseColor(theme.layout.cardBg);
const bgBase = { r: 6, g: 8, b: 28, a: 1 };
const bg =
  bgParsed.a >= 1 ? toHex(bgParsed) : toHex(composite(bgParsed, bgBase));
const bgElevated = lighten(bg, 0.06);
const bgHigh = lighten(bg, 0.12);
const bgDeep = darken(bg, 0.2);

const fg = cssToHex(theme.accents.status.text, bg);
const fgMuted = cssToHex(theme.accents.status.smallMuted, bg);
const accent = cssToHex(theme.menuBarTint, bg);
const accentBright = lighten(accent, 0.15);
const success = cssToHex(theme.status.good, bg);
const danger = cssToHex(theme.status.bad, bg);
const warn = cssToHex(theme.status.warn, bg);

const css = `/*
 * AUTO-GENERATED by scripts/build-slack-css.mjs
 * Source of truth: src/themes/_active.ts → src/themes/${themeName}.ts
 * Loaded at runtime by the patched dist/preload.bundle.js.
 * Re-run \`npm run build:slack-css\` to regenerate; reopen Slack to apply.
 */

:root,
.sk-client-container,
[data-qa-theme],
.p-client_container {
  /* Slack's internal SK design system variables.
     Names move between major releases — coverage is best-effort. */
  --sk_primary_background: ${bg};
  --sk_primary_foreground: ${fg};
  --sk_secondary_background: ${bgElevated};
  --sk_secondary_foreground: ${fg};
  --sk_foreground_high: ${fg};
  --sk_foreground_high_solid: ${fg};
  --sk_foreground_low: ${fgMuted};
  --sk_foreground_low_solid: ${fgMuted};
  --sk_foreground_max: ${fg};
  --sk_foreground_max_solid: ${fg};
  --sk_foreground_min: ${fgMuted};
  --sk_inverted_max: #FFFFFF;
  --sk_inverted_max_solid: #FFFFFF;
  --sk_highlight: ${accent};
  --sk_highlight_hover: ${accentBright};
  --sk_highlight_accent: ${accent};
  --sk_highlight_text: ${fg};
  --sk_overlay: ${bgDeep};
  --sk_raised_floor: ${bgElevated};

  /* Cross-program tints reused from our shared theme tokens. */
  --uber_card_bg: ${bg};
  --uber_card_bg_elevated: ${bgElevated};
  --uber_card_bg_high: ${bgHigh};
  --uber_text: ${fg};
  --uber_text_muted: ${fgMuted};
  --uber_accent: ${accent};
  --uber_success: ${success};
  --uber_danger: ${danger};
  --uber_warn: ${warn};
}

/* ---- Direct selector fallbacks (variable overrides don't always reach) ---- */

/* Workspace switcher rail (leftmost icon column) */
.p-tab_rail,
.p-tab_rail__list {
  background-color: ${bgDeep} !important;
}

/* Channel sidebar */
.p-channel_sidebar,
.p-channel_sidebar__static_list,
.p-channel_sidebar_legacy_styles {
  background-color: ${bg} !important;
  color: ${fg} !important;
}

/* Top nav / search header */
.p-top_nav,
.p-ia_top_nav,
.p-ia_top_nav__container {
  background-color: ${bgDeep} !important;
  color: ${fg} !important;
}

/* Channel list row hover + active */
.p-channel_sidebar__channel:hover,
.p-channel_sidebar__virtual_list_item:hover {
  background-color: ${bgHigh} !important;
}
.p-channel_sidebar__channel--selected,
.p-channel_sidebar__channel--selected:hover {
  background-color: ${accent} !important;
  color: ${fg} !important;
}

/* Message pane body (where messages are read) */
.p-workspace__primary_view,
.p-message_pane,
.p-workspace__primary_view_body {
  background-color: ${bgElevated} !important;
}

/* Message input box at the bottom */
.p-message_input,
.p-message_input_field,
.ql-editor {
  background-color: ${bg} !important;
  color: ${fg} !important;
}

/* Mention badges */
.c-mention_badge,
.p-channel_sidebar__badge--mention {
  background-color: ${danger} !important;
  color: #FFFFFF !important;
}

/* Presence dots (online) */
.c-presence--active {
  color: ${success} !important;
}
`;

await mkdir(outDir, { recursive: true });

let existing = null;
try {
  existing = await readFile(outFile, "utf8");
} catch {
  // First write.
}

if (existing === css) {
  console.log(`(~/.config/slack-uber-theme/theme.css unchanged.)`);
  process.exit(0);
}

await writeFile(outFile, css, "utf8");
console.log(`Generated ${outFile}  (theme: ${themeName}, bg: ${bg}, accent: ${accent})`);
console.log(`Reopen Slack to apply (must have run \`sudo -E node scripts/patch-slack-app.mjs\` once).`);

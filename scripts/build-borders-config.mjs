/**
 * Codegen: src/themes/_active.ts  →  borders/bordersrc
 *
 * Generates the JankyBorders daemon config file from the shared design
 * tokens. Same single-source-of-truth pattern as build-hammerspoon-theme.mjs.
 *
 * bordersrc is a bash script that `borders` sources on startup (and on
 * `borders --load-config`). It exports an `options` array and calls
 * `borders` with them. See the JankyBorders README for the full option
 * list: https://github.com/FelixKratz/JankyBorders
 *
 * Color format: JankyBorders takes colors as 0xAARRGGBB uint32 hex, so
 * we convert CSS rgba() / hex at codegen time.
 */

import * as esbuild from "esbuild";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { readFile, writeFile, mkdir } from "node:fs/promises";
import { execSync, spawn } from "node:child_process";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const activeSrc = join(root, "src", "themes", "_active.ts");
const outDir = join(root, "borders");
const outFile = join(outDir, "bordersrc");

// Bundle the active theme module graph in-memory, dynamic-import via data URL,
// and read `primary` straight off the resulting module. Same pattern as
// build-hammerspoon-theme.mjs — _active.ts is the theme pointer rewritten by
// `npm run theme <name>`, and bundling resolves the re-export chain.
const result = await esbuild.build({
  entryPoints: [activeSrc],
  bundle: true,
  write: false,
  format: "esm",
  target: "es2022",
  logLevel: "silent",
});
const code = result.outputFiles[0].text;
const dataUrl =
  "data:text/javascript;base64," + Buffer.from(code).toString("base64");
const theme = await import(dataUrl);

// CSS color → JankyBorders 0xAARRGGBB hex string.
function cssColorToBordersHex(color) {
  let r, g, b, a;

  const hex = color.match(/^#([0-9a-f]{6})$/i);
  if (hex) {
    const n = parseInt(hex[1], 16);
    r = (n >> 16) & 0xff;
    g = (n >> 8) & 0xff;
    b = n & 0xff;
    a = 255;
  } else {
    const rgba = color.match(
      /^rgba?\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*(?:,\s*([\d.]+)\s*)?\)$/
    );
    if (!rgba) {
      throw new Error(`Cannot parse CSS color: ${color}`);
    }
    r = parseInt(rgba[1], 10);
    g = parseInt(rgba[2], 10);
    b = parseInt(rgba[3], 10);
    a = rgba[4] != null ? Math.round(parseFloat(rgba[4]) * 255) : 255;
  }

  const hh = (n) => n.toString(16).padStart(2, "0");
  return `0x${hh(a)}${hh(r)}${hh(g)}${hh(b)}`;
}

const activeColor = cssColorToBordersHex(theme.primary.active);
const inactiveColor = cssColorToBordersHex(theme.primary.inactive);
const width = theme.primary.width;

const bordersrc = `#!/bin/bash
# AUTO-GENERATED by scripts/build-borders-config.mjs
# Source of truth: src/themes/_active.ts  →  src/themes/<active>.ts
# DO NOT EDIT — your changes will be overwritten on the next \`npm run build\`.
#
# JankyBorders daemon config. Sourced by \`borders\` on startup and on
# \`borders --load-config\`. See https://github.com/FelixKratz/JankyBorders

options=(
  style=round
  width=${width.toFixed(1)}
  hidpi=on
  active_color=${activeColor}
  inactive_color=${inactiveColor}
)

borders "\${options[@]}"
`;

await mkdir(outDir, { recursive: true });

// Skip-if-unchanged: if the generated output is byte-identical to what's
// already on disk, there's nothing to write AND nothing to hot-reload.
// Saves an IPC poke to the running borders daemon on every unchanged
// `npm run build`.
let existing = null;
try {
  existing = await readFile(outFile, "utf8");
} catch {
  // File doesn't exist yet — fall through to write.
}

if (existing === bordersrc) {
  console.log(
    `(${outFile.replace(root + "/", "")} unchanged — skipping write + daemon reload.)`
  );
  process.exit(0);
}

await writeFile(outFile, bordersrc, "utf8");

console.log(
  `Generated ${outFile.replace(root + "/", "")}  (active: ${activeColor}, inactive: ${inactiveColor}, width: ${width})`
);

// Hot reload: if a borders daemon is already running, push the new config
// to it by re-sourcing bordersrc. The `borders` CLI detects the existing
// daemon and updates its settings in place. If nothing is running yet,
// silently skip — first-time setup starts the daemon separately.
try {
  execSync("pgrep -x borders", { stdio: "ignore" });
  const child = spawn("bash", [outFile], {
    detached: true,
    stdio: "ignore",
  });
  child.unref();
  console.log("Reloaded running borders daemon.");
} catch {
  console.log("(No borders daemon running — skipping hot reload.)");
}
